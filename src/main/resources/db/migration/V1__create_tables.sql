CREATE TABLE TB_CITIZEN (
                            ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            NAME VARCHAR2(120) NOT NULL,
                            CPF VARCHAR2(14) NOT NULL UNIQUE,
                            PHONE VARCHAR2(20) NOT NULL,
                            NEIGHBORHOOD VARCHAR2(80) NOT NULL
);

CREATE TABLE TB_COLLECTION_POINT (
                                     ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     NAME VARCHAR2(120) NOT NULL,
                                     CNPJ VARCHAR2(18) NOT NULL UNIQUE,
                                     ADDRESS VARCHAR2(200) NOT NULL,
                                     NEIGHBORHOOD VARCHAR2(80) NOT NULL,
                                     PHONE VARCHAR2(20) NOT NULL,
                                     ACTIVE NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE TB_ACCOUNT (
                            ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            EMAIL VARCHAR2(150) NOT NULL UNIQUE,
                            PASSWORD VARCHAR2(255) NOT NULL,
                            ROLE VARCHAR2(30) NOT NULL,
                            CITIZEN_ID NUMBER(19),
                            COLLECTION_POINT_ID NUMBER(19),
                            CONSTRAINT FK_ACCOUNT_CITIZEN FOREIGN KEY (CITIZEN_ID) REFERENCES TB_CITIZEN(ID),
                            CONSTRAINT FK_ACCOUNT_POINT FOREIGN KEY (COLLECTION_POINT_ID) REFERENCES TB_COLLECTION_POINT(ID)
);

CREATE TABLE TB_CATEGORY (
                             ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             NAME VARCHAR2(80) NOT NULL UNIQUE,
                             DESCRIPTION VARCHAR2(255) NOT NULL
);

CREATE TABLE TB_DONATION (
                             ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             TITLE VARCHAR2(120) NOT NULL,
                             DESCRIPTION VARCHAR2(500) NOT NULL,
                             QUANTITY NUMBER(10) NOT NULL,
                             STATUS VARCHAR2(30) NOT NULL,
                             URGENCY VARCHAR2(20) NOT NULL,
                             AI_SUGGESTED_CATEGORY VARCHAR2(80),
                             AI_TRIAGE_REASON VARCHAR2(300),
                             CREATED_AT TIMESTAMP NOT NULL,
                             REVIEWED_AT TIMESTAMP,
                             REVIEW_NOTES VARCHAR2(300),
                             CITIZEN_ID NUMBER(19) NOT NULL,
                             COLLECTION_POINT_ID NUMBER(19) NOT NULL,
                             CATEGORY_ID NUMBER(19) NOT NULL,
                             CONSTRAINT FK_DONATION_CITIZEN FOREIGN KEY (CITIZEN_ID) REFERENCES TB_CITIZEN(ID),
                             CONSTRAINT FK_DONATION_POINT FOREIGN KEY (COLLECTION_POINT_ID) REFERENCES TB_COLLECTION_POINT(ID),
                             CONSTRAINT FK_DONATION_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES TB_CATEGORY(ID)
);