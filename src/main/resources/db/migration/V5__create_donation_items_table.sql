CREATE TABLE TB_DONATION_ITEM (
                                  ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  NAME VARCHAR2(120) NOT NULL,
                                  QUANTITY NUMBER(10) NOT NULL,
                                  CATEGORY VARCHAR2(30) NOT NULL,
                                  DONATION_ID NUMBER(19) NOT NULL,
                                  CONSTRAINT FK_DONATION_ITEM_DONATION FOREIGN KEY (DONATION_ID) REFERENCES TB_DONATION(ID) ON DELETE CASCADE
);

